const express=require('express');
const cors=require('cors');
require('dotenv').config();
const db=require('./config/db');
const app=express();
app.use(cors({origin:['http://localhost:5173','http://localhost:5174','http://127.0.0.1:5173','http://127.0.0.1:5174'],allowedHeaders:['Content-Type','Authorization'],methods:['GET','POST','PUT','DELETE']}));
app.use(express.json());
app.get('/api/health',async(req,res)=>{try{await db.query('SELECT 1');res.json({message:'MySQL 연결 성공'});}catch(e){res.status(500).json({message:e.message});}});
app.use('/api/users',require('./routes/userRoutes'));
app.use('/api/boards',require('./routes/boardRoutes'));
app.use('/api/join',require('./routes/joinRoutes'));
db.initializeDatabase().then(()=>app.listen(process.env.PORT||5000,()=>console.log('API http://localhost:'+(process.env.PORT||5000)))).catch(err=>{console.error('MySQL 연결/초기화 실패:',err.message);process.exit(1);});
